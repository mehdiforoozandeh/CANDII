"""Declare a store regime's `eval_pairs` — what a mid-training or test-time eval imputes.

D31: on the store the pairing is DECLARED, never inferred, because D16 makes biosample names
opaque ids that nothing may parse. Neither shipped regime declares any, which is why a store-backed
run could not be scored even after `build_eval_units` learned to take a store dataset (t28): the
scorer worked and there was nothing to point it at.

EIC's two splits are not interchangeable and this script keeps them apart:

  --split validation   T_<X> prompts, V_<X> is the ground truth   -> watched during training
  --split test         T_<X> prompts, B_<X> is the ground truth   -> touched once, at the end

That separation is the whole reason `B_` stays clean. A single regime carrying both would put the
test set inside the selection loop, and no amount of care downstream would get it back out.

The pairing is read off the names HERE, in a tool the caller runs deliberately, and written into
the regime as an explicit list. That is the difference D16 cares about: a loader may never parse a
name, but a person may, once, and record the result where it can be audited.

    python tools/declare_eval_pairs.py --in configs/regime.equiv.json \
        --out configs/regime.eic_val.json --split validation
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

#: Which prefix supplies the ground truth for each split. `T_` always prompts.
TRUTH_PREFIX = {"validation": "V_", "test": "B_"}


def pair_by_suffix(train, pool, truth_prefix: str, prompt_prefix: str = "T_"):
    """`T_K562` <-> `V_K562`, matched on the suffix after the first prefix.

    Returns `(pairs, unpaired_prompts)`. A `T_` with no counterpart is REPORTED rather than
    dropped silently: it still occupies a cycle slot in the eval loop, and a caller who expected
    38 targets and got 26 should learn that here and not from a puzzling `n_targets`.
    """
    truth = {b[len(truth_prefix):]: b for b in pool if b.startswith(truth_prefix)}
    pairs, unpaired = [], []
    for t in sorted(x for x in train if x.startswith(prompt_prefix)):
        suf = t[len(prompt_prefix):]
        if suf in truth:
            pairs.append([t, truth[suf]])
        else:
            unpaired.append(t)
    return pairs, unpaired


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    p.add_argument("--in", dest="src", required=True, help="regime json to read")
    p.add_argument("--out", required=True, help="regime json to write")
    p.add_argument("--split", choices=sorted(TRUTH_PREFIX), required=True)
    p.add_argument("--comment", default="")
    args = p.parse_args(argv)

    obj = json.loads(Path(args.src).read_text(encoding="utf-8"))
    bios = obj.get("biosamples") or {}
    train = list(bios.get("train") or [])
    # The counterpart may sit in either list: a regime written for one split lists only that
    # split's truth biosamples under `eval`, and one written for neither lists both.
    pool = list(bios.get("eval") or []) + train
    prefix = TRUTH_PREFIX[args.split]
    pairs, unpaired = pair_by_suffix(train, pool, prefix)
    if not pairs:
        raise SystemExit(f"no {prefix} counterpart for any of the {len(train)} training "
                         f"biosamples in {args.src}; nothing to declare")

    obj["biosamples"] = {"train": train, "eval": [b for _, b in pairs]}
    obj["eval_pairs"] = pairs
    obj["_comment"] = (args.comment or
                       f"GENERATED by tools/declare_eval_pairs.py --split {args.split} from "
                       f"{Path(args.src).name}. {len(pairs)} pairs; {prefix} supplies the truth. "
                       f"{'EIC validation -- watched during training.' if args.split == 'validation' else 'EIC TEST -- touch once, at the end. Never in a selection loop.'}")
    Path(args.out).write_text(json.dumps(obj, indent=2) + "\n", encoding="utf-8")

    print(f"[pairs] {args.split}: {len(pairs)} pairs written to {args.out}")
    print(f"[pairs]   e.g. {pairs[:3]}")
    if unpaired:
        print(f"[pairs]   {len(unpaired)} training biosamples have no {prefix} counterpart and are "
              f"NOT targets: {unpaired[:5]}{' …' if len(unpaired) > 5 else ''}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
