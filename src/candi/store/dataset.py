class StoreDataset(IterableDataset):
    """Batches from a `CorpusStore` under a `Regime`. One biosample per batch, as before.

    Use it with `DataLoader(ds, batch_size=None, num_workers=N)` — like `CandiKitH5Dataset` it
    yields whole batches, and shards them across workers itself.
    """

    def __init__(
        self,
        regime: Regime | Path | str,
        *,
        corpus: Optional[CorpusStore] = None,
        train: bool = True,
        batch_size: int = 8,
        dsf_sampling: str = "uniform",
        shuffle: Optional[bool] = None,
        seed: Optional[int] = None,
        run_seed: Optional[int] = None,
        deterministic: Optional[bool] = None,
        biosamples: Optional[Sequence[str]] = None,
        chroms: Optional[Sequence[str]] = None,
        cell_cond: str = "off",
        meta_missing: str = "unavailable",
        require_dna: bool = False,
    ) -> None:
        super().__init__()
        self.regime = regime if isinstance(regime, Regime) else Regime.from_file(regime)
        self.train = bool(train)
        self.split = "train" if self.train else "eval"
        self.batch_size = int(batch_size)
        self.dsf_sampling = str(dsf_sampling)
        self.shuffle = bool(self.train if shuffle is None else shuffle)
        self.seed = int(self.regime.seed if seed is None else seed)
        self.run_seed = int(self.seed if run_seed is None else run_seed)
        # D22 — evaluation is counter-based by default; training is free-running by default.
        self.deterministic = bool((not self.train) if deterministic is None else deterministic)
        self.meta_missing = str(meta_missing)
        self.require_dna = bool(require_dna)
        if self.dsf_sampling not in ("off", "uniform", "x_eq_y", "upsample_only"):
            raise StoreError(f"unknown dsf sampling mode {self.dsf_sampling!r}")
        if self.meta_missing not in ("unavailable", "error"):
            raise StoreError(f"meta_missing must be 'unavailable' or 'error', got {meta_missing!r}")
        if str(cell_cond) != "off":
            raise StoreError(
                "cell_cond is not carried into the store path yet. The 5th metadata row keys on a "
                "cell type derived by splitting a T_/V_/B_ prefix (`dataset.py::base_cell_type`), "
                "and D16 makes store biosample names opaque ids that nothing may parse. Deciding "
                "what a cell identity is for `A549_nonrep` is a task, not a default."
            )
        self.cell_cond = "off"
        self.meta_rows = META_ROWS

        self.corpus = corpus if corpus is not None else CorpusStore(self.regime.store)
        self.regime.validate_against(self.corpus)

        # -- the surface `train.py` / `eval.py` read off the dataset ---------------------------
        self.assays: List[str] = list(self.regime.assays)
        self.num_assays = len(self.assays)
        self.signal_dim = self.num_assays
        self.context_bins = int(self.regime.context_bins)
        self.resolution = int(self.corpus.resolution)
        self.train_chroms: Tuple[str, ...] = tuple(self.regime.train_chroms)
        self.eval_chroms: Tuple[str, ...] = tuple(self.regime.eval_chroms)
        self.dsf_list: Tuple[int, ...] = tuple(
            int(x) for x in self.regime.dsf.levels
        ) if self.regime.dsf.policy == "discrete" else ()

        pool = list(biosamples) if biosamples is not None else list(self.regime.biosamples(self.split))
        if not pool:
            pool = list(self.corpus.biosamples)
        absent = [b for b in pool if b not in self.corpus]
        if absent:
            raise StoreError(f"biosample(s) {absent} are not in {self.corpus.root}")
        self.biosample_pool: List[str] = pool

        self._windows: List[Tuple[str, int]] = self.regime.windows(
            self.corpus, self.split, chroms=chroms
        )
        self._availability: Dict[str, np.ndarray] = {}
        self._meta: Dict[str, np.ndarray] = {}
        self._control_meta: Dict[str, Optional[np.ndarray]] = {}
        self._gaps: List[str] = []
        for name in self.biosample_pool:
            self._build_meta(name)
        if self._gaps:
            print(
                f"[store] {len(self._gaps)} (biosample, assay) column(s) are present on disk but "
                f"carry incomplete metadata and are emitted as MISSING (D19 — nothing is "
                f"fabricated). First few: {self._gaps[:5]}",
                flush=True,
            )
        if self.require_dna and not self.corpus.genome.has_dna:
            raise StoreError(
                f"{self.corpus.genome.dna_path}: missing and require_dna=True. Build the genome "
                f"layer (t7) or accept an all-zero x_dna."
            )
        if not self.corpus.genome.has_dna:
            print(
                f"[store] no {self.corpus.genome.dna_path} — x_dna is all-zero, which the model "
                f"reads as 'every base unknown'. Fine for a plumbing test, wrong for training.",
                flush=True,
            )
        if not self.regime.mask_available(self.corpus):
            print(
                "[store] no genome/mask.h5 — every window is eligible (D12 cannot be applied). "
                "Blacklisted and N-heavy windows are therefore IN the plan.",
                flush=True,
            )

    # -- metadata (D19: nothing is fabricated) --------------------------------------------------

    def _build_meta(self, name: str) -> None:
        """Per-assay `[depth_log2, assay_id, read_length, run_type_id]` at DSF1, plus availability.

        A column is available only when the store has it **and** the manifest gives all four
        covariates. A partially-known column cannot be expressed: the encoder derives availability
        from rows 0-3 (`encoder.py::_infer_availability_from_meta`), so one `-1` there marks the
        whole assay absent while the signal says present, and `_prepare_signal` raises on the
        disagreement. Emitting the column as MISSING is the honest reading of "we do not know how
        deep this track is", and every such column is printed once at construction.
        """
        bs = self.corpus[name]
        avail = np.zeros(self.num_assays, dtype=bool)
        meta = np.full((META_ROWS, self.num_assays), float(MISSING), dtype=np.float32)
        for i, assay in enumerate(self.assays):
            if not bs.has(assay, "counts"):
                continue
            rec = self.corpus.track_meta(name, assay)
            if rec is None:
                raise StoreError(
                    f"{self.corpus.root}: no manifest.json, so no depth / read_length / run_type "
                    f"for any track. Run `python -m candi.store build-manifest` — the covariates "
                    f"are four of the model's inputs, not decoration."
                )
            row = self._meta_row(rec, i)
            if row is None:
                self._gaps.append(f"{name}/{assay}")
                if self.meta_missing == "error":
                    raise StoreError(
                        f"{name}/{assay}: the manifest has no complete "
                        f"depth/read_length/run_type. meta_missing='error' refuses to continue."
                    )
                continue
            meta[:, i] = row
            avail[i] = True
        if not avail.any():
            raise StoreError(
                f"{name}: not one declared assay is both present and fully described. Declared "
                f"{self.assays}; the store has {bs.assays('counts')}."
            )
        self._availability[name] = avail
        self._meta[name] = meta
        self._control_meta[name] = self._build_control_meta(name, bs)

    def _meta_row(self, rec: Mapping[str, Any], assay_id: int) -> Optional[np.ndarray]:
        """One manifest track record -> one metadata column, or None when it is not complete.

        `run_type` is the manifest's normalized `single-ended` / `paired-ended`
        (`manifest.py::_norm_run_type`) mapped to `0` / `1`, the encoding
        `prep/handler.py::make_bios_tensor_Counts` uses. An unrecognized string is **not** guessed
        at as single-ended — that fallback is exactly what D19 deleted.
        """
        depth, readlen, runtype = rec.get("depth"), rec.get("read_length"), rec.get("run_type")
        if depth is None or readlen is None or runtype is None:
            return None
        try:
            depth, readlen = float(depth), float(readlen)
        except (TypeError, ValueError):
            return None
        if depth <= 0 or readlen <= 0:
            return None
        rt = _RUN_TYPE_ID.get(str(runtype))
        if rt is None:
            return None
        return np.array(
            [math.log2(depth), float(assay_id), readlen, float(rt)], dtype=np.float32
        )

    def _build_control_meta(self, name: str, bs) -> Optional[np.ndarray]:
        """`[4, 1]` for the `chipseq-control` column, or None when this biosample has no control.

        `assay_id` is `num_assays` — the control's own id, exactly as `prep/bake.py` writes it and
        as `encoder.py`'s `assay_embedding` (sized `num_assays + 3`) expects.
        """
        if not bs.has_control:
            return None
        rec = self.corpus.track_meta(name, L.CONTROL_TRACK)
        if not rec:
            return None
        row = self._meta_row(rec, self.num_assays)
        return None if row is None else row.reshape(META_ROWS, 1)

    # -- the window/batch plan ------------------------------------------------------------------

    def _batches(self, rng: random.Random) -> List[Tuple[str, List[int]]]:
        """`[(biosample, [window index, …]), …]` — one biosample per batch, as the old path.

        Deterministic given `rng`, and every worker computes the same list before sharding, so a
        window lands in exactly one worker no matter how many there are.
        """
        out: List[Tuple[str, List[int]]] = []
        idx = list(range(len(self._windows)))
        if self.train:
            if self.shuffle:
                rng.shuffle(idx)
            for pos in range(0, len(idx), self.batch_size):
                chunk = idx[pos:pos + self.batch_size]
                if len(chunk) < self.batch_size:
                    continue                      # drop_last, exactly as CandiKitH5Dataset does
                out.append((rng.choice(self.biosample_pool), chunk))
        else:
            for name in sorted(self.biosample_pool):
                order = list(idx)
                if self.shuffle:
                    rng.shuffle(order)
                for pos in range(0, len(order), self.batch_size):
                    out.append((name, order[pos:pos + self.batch_size]))
            if self.shuffle:
                rng.shuffle(out)
        return out

    def estimate_steps_per_epoch(self) -> int:
        return max(1, len(self._batches(random.Random(self.seed))))

    def __len__(self) -> int:
        return len(self._batches(random.Random(self.seed)))

    # -- DSF sampling (D23) ---------------------------------------------------------------------

    def _dsf_rng(self, name: str, assay: str, chrom: str, start: int,
                 free: np.random.Generator) -> np.random.Generator:
        if not self.deterministic:
            return free
        return np.random.default_rng(
            draw_seed(self.run_seed, name, assay, chrom, start, DSF_STREAM_TAG)
        )

    def _sample_dsf(self, name: str, chrom: str, start: int,
                    free: np.random.Generator) -> Tuple[np.ndarray, np.ndarray]:
        """Per-assay `(x_dsf, y_dsf)`, mirroring `dataset.py::_sample_xy_dsf`'s four modes.

        In deterministic mode the draw itself is counter-based, otherwise a shuffled eval would
        thin the same window at a different depth each run and D22 would buy nothing.
        """
        pol = self.regime.dsf
        x = np.ones(self.num_assays, dtype=np.float64)
        y = np.ones(self.num_assays, dtype=np.float64)
        if self.dsf_sampling == "off" or pol.is_trivial:
            return x, y
        for i, assay in enumerate(self.assays):
            rng = self._dsf_rng(name, assay, chrom, start, free)
            xi = pol.sample(rng)
            if self.dsf_sampling == "x_eq_y":
                yi = xi
            elif self.dsf_sampling == "upsample_only":
                if pol.policy == "discrete":
                    choices = [d for d in pol.levels if d >= xi] or [xi]
                    yi = float(choices[int(rng.integers(len(choices)))])
                else:
                    yi = float(np.exp(rng.uniform(np.log(xi), np.log(max(xi, pol.dsf_max)))))
            else:
                yi = pol.sample(rng)
            x[i], y[i] = xi, yi
        return x, y

    # -- thinning -------------------------------------------------------------------------------

    def _thin(self, counts: np.ndarray, dsf: float, name: str, assay: str, chrom: str,
              start: int, free: np.random.Generator) -> np.ndarray:
        if float(dsf) == 1.0:
            return counts
        rng = (
            np.random.default_rng(draw_seed(self.run_seed, name, assay, chrom, start,
                                            dsf_milli(dsf)))
            if self.deterministic
            else free
        )
        return thin_counts(counts, dsf, rng)

    # -- iteration ------------------------------------------------------------------------------

    def __iter__(self) -> Iterator[Dict[str, Any]]:
        info = torch.utils.data.get_worker_info()
        # D22 (training half): the free-running stream is seeded from the DataLoader worker seed,
        # so two workers never draw the same thinning noise and a re-run is not reproducible —
        # which is fine, because training noise is not a measurement.
        free = np.random.default_rng(int(info.seed) if info is not None else self.seed)
        batches = self._batches(random.Random(self.seed))
        if info is not None:
            batches = batches[info.id::info.num_workers]
        for name, widx in batches:
            yield self._make_batch(name, widx, free)

    def _make_batch(self, name: str, widx: Sequence[int],
                    free: np.random.Generator) -> Dict[str, Any]:
        bs = self.corpus[name]
        B, Lb, F = len(widx), self.context_bins, self.num_assays
        R, Lbp = META_ROWS, self.context_bins * self.resolution
        avail_mask = self._availability[name]
        meta1 = self._meta[name]
        present = [a for i, a in enumerate(self.assays) if avail_mask[i]]
        cols = [i for i in range(F) if avail_mask[i]]

        # Same construction, same fill values, same dtypes as `dataset.py::CandiKitH5Dataset`.
        x_data = torch.full((B, Lb, F), float(MISSING))
        y_data = torch.full((B, Lb, F), float(MISSING))
        x_meta = torch.full((B, R, F), float(MISSING))
        y_meta = torch.full((B, R, F), float(MISSING))
        x_avail = torch.zeros(B, F, dtype=torch.float32)
        y_avail = torch.zeros(B, F, dtype=torch.float32)
        y_pval = torch.zeros(B, Lb, F)
        y_peaks = torch.zeros(B, Lb, F)
        x_dna = torch.zeros(B, Lbp, 4)
        control_data = torch.zeros(B, Lb, 1)
        control_meta = torch.zeros(B, R, 1)
        control_avail = torch.zeros(B, 1)
        region_type = torch.full((B,), REGION_TILE, dtype=torch.uint8)
        x_dsf_t = torch.ones(B, F, dtype=torch.int64)
        y_dsf_t = torch.ones(B, F, dtype=torch.int64)

        want_pval = "pval" in self.regime.kinds and "pval" in bs.kinds
        want_peaks = "peaks" in self.regime.kinds and "peaks" in bs.kinds

        for j, wi in enumerate(widx):
            chrom, start = self._windows[wi]
            end = start + Lb
            xd, yd = self._sample_dsf(name, chrom, start, free)
            x_dsf_t[j] = torch.from_numpy(np.rint(xd).astype(np.int64))
            y_dsf_t[j] = torch.from_numpy(np.rint(yd).astype(np.int64))

            if present:
                block = bs.counts(chrom, start, end, assays=present)      # (L, len(present))
                for k, assay in enumerate(present):
                    fi = cols[k]
                    col = block[:, k]
                    xc = self._thin(col, xd[fi], name, assay, chrom, start, free)
                    yc = self._thin(col, yd[fi], name, assay, chrom, start, free)
                    x_data[j, :, fi] = torch.from_numpy(np.asarray(xc, dtype=np.float32))
                    y_data[j, :, fi] = torch.from_numpy(np.asarray(yc, dtype=np.float32))
                    x_meta[j, :, fi] = torch.from_numpy(self._depth_adjusted(meta1[:, fi], xd[fi]))
                    y_meta[j, :, fi] = torch.from_numpy(self._depth_adjusted(meta1[:, fi], yd[fi]))
                    x_avail[j, fi] = 1.0
                    y_avail[j, fi] = 1.0

                if want_pval:
                    have = [a for a in present if bs.has(a, "pval")]
                    if have:
                        pv = bs.pval(chrom, start, end, assays=have)
                        for k, assay in enumerate(have):
                            y_pval[j, :, self.assays.index(assay)] = torch.from_numpy(pv[:, k])
                if want_peaks:
                    have = [a for a in present if bs.has(a, "peaks")]
                    if have:
                        pk = bs.peaks(chrom, start, end, assays=have)
                        for k, assay in enumerate(have):
                            y_peaks[j, :, self.assays.index(assay)] = torch.from_numpy(
                                pk[:, k].astype(np.float32)
                            )

            if bs.has_control:
                ctrl = bs.control(chrom, start, end)[:, 0]     # never thinned: control_x_dsf == 1
                control_data[j, :, 0] = torch.from_numpy(ctrl.astype(np.float32))
                cm = self._control_meta.get(name)
                if cm is not None:
                    control_meta[j] = torch.from_numpy(cm)
                control_avail[j, 0] = 1.0 if bool((control_data[j] != 0).any().item()) else 0.0

            if self.corpus.genome.has_dna:
                x_dna[j] = torch.from_numpy(
                    self.corpus.genome.dna_onehot(chrom, start * self.resolution,
                                                  end * self.resolution)
                )

        return {
            "x_data": x_data,
            "x_meta": x_meta,
            "x_avail": x_avail,
            "x_dna": x_dna,
            "y_data": y_data,
            "y_meta": y_meta,
            "y_avail": y_avail,
            "y_pval": y_pval,
            "y_peaks": y_peaks,
            "control_data": control_data,
            "control_meta": control_meta,
            "control_avail": control_avail,
            "x_dsf": x_dsf_t,
            "y_dsf": y_dsf_t,
            "control_x_dsf": torch.ones(B, dtype=torch.int64),
            "biosample_name": name,
            "region_type": region_type,
            "window_idx": torch.tensor(list(widx), dtype=torch.int64),
        }

    @staticmethod
    def _depth_adjusted(row: np.ndarray, dsf: float) -> np.ndarray:
        """`[depth_log2 - log2(d), assay_id, read_length, run_type_id]`.

        Thinning by `d` divides the depth by `d`, and the model's depth covariate is `log2` of it,
        so the row must move with the signal — `prep/bake.py`'s F4 gate is exactly this identity
        (`meta_dsf{d}[0] == meta_dsf1[0] - log2(d)`), and a batch that thins the counts but not
        the covariate teaches the model that depth does not predict scale.
        """
        out = np.array(row, dtype=np.float32, copy=True)
        if float(dsf) != 1.0:
            out[0] = np.float32(float(out[0]) - math.log2(float(dsf)))
        return out
